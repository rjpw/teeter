package compose

import (
	"bytes"
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/rjpw/teeter/internal/buildctx"
	"github.com/rjpw/teeter/internal/cache"
	"github.com/rjpw/teeter/internal/manifest"
)

// SQLFiles holds the generated SQL files.
type SQLFiles struct {
	CombinedSQL string // teeter-combined.sql
}

// GenerateSQLFiles generates the combined SQL file from build context and manifest.
func GenerateSQLFiles(ctx context.Context, bc *buildctx.BuildContext, c cache.Cache, m *manifest.Manifest) (SQLFiles, error) {
	var combined bytes.Buffer

	// Header
	combined.WriteString("-- Generated by teeter - DO NOT EDIT\n")
	combined.WriteString("-- Combined SQL for database initialization\n\n")

	// 1. Custom migrations from manifest
	if m != nil {
		for _, mig := range m.Database.Migrations {
			content, err := readSQLFile(mig, m)
			if err != nil {
				return SQLFiles{}, fmt.Errorf("read migration %s: %w", mig, err)
			}
			combined.WriteString(fmt.Sprintf("-- Migration: %s\n", mig))
			combined.WriteString(content)
			combined.WriteString("\n\n")
		}

		// 2. Custom seed data from manifest
		for _, seed := range m.Database.Seed {
			content, err := readSQLFile(seed, m)
			if err != nil {
				return SQLFiles{}, fmt.Errorf("read seed %s: %w", seed, err)
			}
			combined.WriteString(fmt.Sprintf("-- Seed: %s\n", seed))
			combined.WriteString(content)
			combined.WriteString("\n\n")
		}
	}

	// 3. Module SQL files from cache
	if bc != nil && bc.Resolution != nil {
		for _, name := range bc.Resolution.BuildOrder {
			mod, ok := bc.Resolution.Modules[name]
			if !ok {
				continue
			}

			srcPath, err := c.GetModule(ctx, name, mod.Version)
			if err != nil {
				continue
			}

			moduleSQLDir := filepath.Join(srcPath, "modules", name, "sql")
			if _, err := os.Stat(moduleSQLDir); err != nil {
				continue
			}

			files, err := os.ReadDir(moduleSQLDir)
			if err != nil {
				continue
			}

			for _, f := range files {
				if !strings.HasSuffix(f.Name(), ".sql") {
					continue
				}
				content, err := os.ReadFile(filepath.Join(moduleSQLDir, f.Name()))
				if err != nil {
					continue
				}
				combined.WriteString(fmt.Sprintf("-- Module %s: %s\n", name, f.Name()))
				combined.WriteString(string(content))
				combined.WriteString("\n\n")
			}
		}
	}

	return SQLFiles{
		CombinedSQL: combined.String(),
	}, nil
}

// readSQLFile reads a SQL file, resolving relative to manifest directory.
func readSQLFile(path string, m *manifest.Manifest) (string, error) {
	// For now, assume path is relative to current working directory
	// In a real implementation, we'd need the manifest directory
	if !filepath.IsAbs(path) {
		// Try to find relative to CWD
		if _, err := os.Stat(path); err == nil {
			data, err := os.ReadFile(path)
			if err != nil {
				return "", err
			}
			return string(data), nil
		}
	}

	data, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	return string(data), nil
}
