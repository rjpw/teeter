package compose

import (
	"bytes"
	"text/template"
)

// DockerfileData holds the data for Dockerfile template.
type DockerfileData struct {
	BuildJobs     int
	CCacheMaxSize string
	BuildMemory   string
	BuildCPUs     string
	Registry      string
	ACCommit      string
	ModulesHash   string
	FullHash      string
}

// GenerateDockerfile generates the multi-stage Dockerfile for the layered build strategy.
func GenerateDockerfile(data DockerfileData) (string, error) {
	// Set defaults
	if data.BuildJobs == 0 {
		data.BuildJobs = 2
	}
	if data.CCacheMaxSize == "" {
		data.CCacheMaxSize = "1G"
	}
	if data.BuildMemory == "" {
		data.BuildMemory = "4G"
	}
	if data.BuildCPUs == "" {
		data.BuildCPUs = "2"
	}
	if data.Registry == "" {
		data.Registry = "teeter"
	}

	const dockerfileTemplate = `# syntax = docker/dockerfile:1.4
# Generated by teeter - DO NOT EDIT

# ============================================================
# STAGE 1: BUILDER BASE (reused across module rebuilds)
# ============================================================
FROM ubuntu:22.04 AS builder-base

# Install build dependencies
RUN apt-get update && apt-get install -y --no-install-recommends \
    cmake gcc g++ make clang git ccache \
    libssl-dev libreadline-dev libboost-all-dev \
    libmariadb-dev libbz2-dev libzstd-dev \
    && rm -rf /var/lib/apt/lists/*

# Configure ccache
ENV CCACHE_DIR=/root/.ccache \
    CCACHE_MAXSIZE={{.CCacheMaxSize}} \
    CCACHE_COMPRESS=1 \
    CCACHE_NOHASHDIR=1

WORKDIR /azerothcore

# ============================================================
# STAGE 2: AC SOURCE (cached per AC commit)
# ============================================================
FROM builder-base AS ac-source

# AC source copied from build context (linked from cache)
COPY azerothcore/ ./azerothcore/

# Pre-build step: configure only (fast, cached)
ARG BUILD_JOBS={{.BuildJobs}}
RUN mkdir -p build && cd build && \
    cmake ../azerothcore -DCMAKE_INSTALL_PREFIX=/azerothcore/env/dist \
             -DTOOLS=0 -DSCRIPTS=0 \
             -DCMAKE_BUILD_TYPE=RelWithDebInfo

# ============================================================
# STAGE 3: MODULES BUILD (rebuilds when modules change)
# ============================================================
FROM ac-source AS modules-build

# Copy external module sources
COPY modules/ ./modules/

# Build modules (incremental via ccache)
RUN cd build && make -j${BUILD_JOBS} install

# ============================================================
# STAGE 4: RUNTIME BASE
# ============================================================
FROM ubuntu:22.04 AS runtime-base

# Install runtime dependencies only
RUN apt-get update && apt-get install -y --no-install-recommends \
    libssl3 libreadline8 \
    libboost-system1.74 libboost-filesystem1.74 libboost-thread1.74 \
    libboost-program-options1.74 libboost-iostreams1.74 \
    libmariadb3 libbz2-1.0 libzstd1 mysql-client \
    && rm -rf /var/lib/apt/lists/*

# ============================================================
# STAGE 5: RUNTIME (rebuilds on config/SQL change)
# ============================================================
FROM runtime-base AS runtime

# Copy built binaries from modules stage
COPY --from=modules-build /azerothcore/env/dist /azerothcore/env/dist

# Copy configuration
COPY teeter.yaml /azerothcore/env/dist/teeter.yaml
COPY env.ac /azerothcore/env/dist/env.ac
COPY sql/ /azerothcore/sql/

# Copy entrypoint
COPY docker/entrypoint.sh /entrypoint.sh
RUN chmod +x /entrypoint.sh

# Create acore user
RUN useradd -r -s /bin/bash -d /azerothcore acore && \
    chown -R acore:acore /azerothcore
USER acore

WORKDIR /azerothcore/env/dist

ENTRYPOINT ["/entrypoint.sh"]
`

	tmpl, err := template.New("dockerfile").Parse(dockerfileTemplate)
	if err != nil {
		return "", err
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return "", err
	}

	return buf.String(), nil
}
