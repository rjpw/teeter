// generateRandomPassword generates a random base64-encoded password of given length.
func generateRandomPassword(length int) string {
	b := make([]byte, length)
	if _, err := rand.Read(b); err != nil {
		// Fallback to a deterministic but unique value
		return fmt.Sprintf("teeter-%d", time.Now().UnixNano())
	}
	return base64.URLEncoding.EncodeToString(b)[:length]
}
func WriteEnvFiles(bc *buildctx.BuildContext, ef EnvFiles) error {
	// Write env.ac
	envACPath := filepath.Join(bc.Path, "env.ac")
	if err := os.WriteFile(envACPath, []byte(ef.EnvAC), 0644); err != nil {
		return fmt.Errorf("write env.ac: %w", err)
	}

	// Write .env
	envPath := filepath.Join(bc.Path, ".env")
	if err := os.WriteFile(envPath, []byte(ef.Env), 0644); err != nil {
		return fmt.Errorf("write .env: %w", err)
	}

	// Helper to write config file, removing any existing directory
	writeConfig := func(path, content string) error {
		// SAFETY: Validate path is not empty and not a dangerous location
		if path == "" {
			return fmt.Errorf("empty path provided")
		}
		absPath, err := filepath.Abs(path)
		if err != nil {
			return fmt.Errorf("resolve absolute path: %w", err)
		}
		// Prevent operations on root or home directory
		if absPath == "/" || absPath == string(os.PathSeparator) {
			return fmt.Errorf("refusing to operate on root directory")
		}
		// Ensure path is within build context
		buildCtxAbs, err := filepath.Abs(bc.Path)
		if err != nil {
			return fmt.Errorf("resolve build context: %w", err)
		}
		if !strings.HasPrefix(absPath, buildCtxAbs+string(os.PathSeparator)) {
			return fmt.Errorf("path %s outside build context %s", absPath, buildCtxAbs)
		}

		// Create parent directory
		if err := os.MkdirAll(filepath.Dir(absPath), 0755); err != nil {
			return err
		}
		// Remove if exists as directory
		if info, err := os.Stat(absPath); err == nil && info.IsDir() {
			if err := os.RemoveAll(absPath); err != nil {
				return err
			}
		}
		return os.WriteFile(absPath, []byte(content), 0644)
	}

	// Write dbimport.conf
	dbimportConfPath := filepath.Join(bc.Path, "sql", "teeter-dbimport.conf")
	if err := writeConfig(dbimportConfPath, ef.DbimportConf); err != nil {
		return fmt.Errorf("write dbimport.conf: %w", err)
	}

	// Write authserver.conf
	authserverConfPath := filepath.Join(bc.Path, "sql", "teeter-authserver.conf")
	if err := writeConfig(authserverConfPath, ef.AuthserverConf); err != nil {
		return fmt.Errorf("write authserver.conf: %w", err)
	}

	// Write worldserver.conf
	worldserverConfPath := filepath.Join(bc.Path, "sql", "teeter-worldserver.conf")
	if err := writeConfig(worldserverConfPath, ef.WorldserverConf); err != nil {
		return fmt.Errorf("write worldserver.conf: %w", err)
	}

	return nil
}
