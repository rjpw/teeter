package compose

import (
	"bytes"
	"fmt"
	"sort"

	"github.com/rjpw/teeter/internal/buildctx"
	"github.com/rjpw/teeter/internal/manifest"
)

// EnvFiles holds the generated environment files.
type EnvFiles struct {
	EnvAC string // env.ac - AC runtime config
	Env   string // .env - secrets and overrides
}

// GenerateEnvFiles generates env.ac and .env files from build context and manifest.
func GenerateEnvFiles(bc *buildctx.BuildContext, m *manifest.Manifest) (EnvFiles, error) {
	var envAC bytes.Buffer
	var env bytes.Buffer

	// Generate env.ac
	envAC.WriteString("# Generated by teeter - DO NOT EDIT\n")
	envAC.WriteString("# AC Runtime Configuration\n\n")

	// Database config
	envAC.WriteString("# Database\n")
	envAC.WriteString("DB_HOST=ac-database\n")
	envAC.WriteString("DB_PORT=3306\n")
	envAC.WriteString("DB_USER=acore\n")
	envAC.WriteString("DB_PASSWORD=${MYSQL_PASSWORD}\n\n")

	// Server ports
	envAC.WriteString("# Server Ports\n")
	envAC.WriteString("WORLD_PORT=8085\n")
	envAC.WriteString("AUTH_PORT=3724\n\n")

	// Manifest environment variables
	if m != nil && len(m.Environment.Vars) > 0 {
		envAC.WriteString("# Manifest Environment Variables\n")
		keys := make([]string, 0, len(m.Environment.Vars))
		for k := range m.Environment.Vars {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			envAC.WriteString(fmt.Sprintf("%s=%s\n", k, m.Environment.Vars[k]))
		}
		envAC.WriteString("\n")
	}

	// Module configurations
	if m != nil && len(m.Modules) > 0 {
		envAC.WriteString("# Module Configurations\n")
		for _, mod := range m.Modules {
			if len(mod.Config.Env) > 0 {
				envAC.WriteString(fmt.Sprintf("# Module: %s\n", mod.Name))
				keys := make([]string, 0, len(mod.Config.Env))
				for k := range mod.Config.Env {
					keys = append(keys, k)
				}
				sort.Strings(keys)
				for _, k := range keys {
					envAC.WriteString(fmt.Sprintf("%s=%s\n", k, mod.Config.Env[k]))
				}
				envAC.WriteString("\n")
			}
		}
	}

	// Generate .env (secrets and overrides)
	env.WriteString("# Generated by teeter - DO NOT EDIT\n")
	env.WriteString("# Secrets and Overrides\n\n")

	if m != nil && len(m.Environment.Secrets) > 0 {
		env.WriteString("# Secrets (set these before running)\n")
		for _, secret := range m.Environment.Secrets {
			env.WriteString(fmt.Sprintf("%s=\n", secret))
		}
		env.WriteString("\n")
	}

	// Add required secrets
	requiredSecrets := []string{
		"MYSQL_ROOT_PASSWORD",
		"MYSQL_PASSWORD",
	}
	env.WriteString("# Required\n")
	for _, secret := range requiredSecrets {
		// Only add if not already in manifest secrets
		found := false
		if m != nil {
			for _, s := range m.Environment.Secrets {
				if s == secret {
					found = true
					break
				}
			}
		}
		if !found {
			env.WriteString(fmt.Sprintf("%s=\n", secret))
		}
	}
	env.WriteString("\n")

	// Client data path (expanded)
	if m != nil && m.ClientData.WoWClientMapsPath != "" {
		env.WriteString("# Client Data\n")
		env.WriteString(fmt.Sprintf("WOW_CLIENT_PATH=%s\n", m.ClientData.WoWClientMapsPath))
		env.WriteString("\n")
	}

	return EnvFiles{
		EnvAC: envAC.String(),
		Env:   env.String(),
	}, nil
}

// WriteEnvFiles writes the environment files to the build context.
func WriteEnvFiles(bc *buildctx.BuildContext, ef EnvFiles) error {
	// Write env.ac
	envACPath := "/azerothcore/env.dist/env.ac"
	// This will be copied into the build context by the caller
	_ = envACPath

	return nil
}
